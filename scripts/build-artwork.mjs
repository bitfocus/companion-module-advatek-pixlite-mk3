import { readFile, writeFile, mkdir } from "node:fs/promises";
import sharp from "sharp";
import { createHash } from "node:crypto";

// Sharp runs only during generation; runtime presets embed PNGs and need no fonts.
const root = new URL("../", import.meta.url);
const mapping = JSON.parse(
  await readFile(new URL("assets/artwork.json", root)),
);
const rawIcon = async (name) => {
  const svg = await readFile(
    new URL(`assets/operator-icons/${name}.svg`, root),
    "utf8",
  ).catch(() =>
    readFile(new URL(`assets/primeicons/${name}.svg`, root), "utf8"),
  );
  if (!/viewBox="0 0 24 24"/.test(svg))
    throw new Error(`Unexpected viewBox: ${name}`);
  return (
    svg
      .replace(/^[\s\S]*?<svg[^>]*>/, "")
      .replace(/<\/svg>\s*$/, "")
      // Apply theme colour without modifying the upstream SVG source.
      .replace(/\sfill="(?:black|#000000|#000)"/g, "")
  );
};
const icons = Object.fromEntries(
  await Promise.all(
    Object.entries(mapping).map(async ([id, name]) => [
      id,
      await rawIcon(name),
    ]),
  ),
);
const badges = {
  stale: await rawIcon("clock"),
  fault: await rawIcon("exclamation-triangle"),
};
const artwork = {};
const pngs = [];
for (const [id, path] of Object.entries(icons)) {
  artwork[id] = {};
  for (const theme of ["dark", "light"]) {
    artwork[id][theme] = {};
    const background = theme === "dark" ? "#353436" : "#FFFFFF";
    const foreground = theme === "dark" ? "#FFFFFF" : "#353436";
    const stale = theme === "dark" ? "#B8B7B9" : "#78787A";
    for (const state of ["idle", "active", "stale", "fault"]) {
      const edge = {
        idle: theme === "dark" ? "#626164" : "#CECCCF",
        active: "#F15A2C",
        stale,
        fault: "#B42318",
      }[state];
      const fill = state === "stale" ? stale : foreground;
      const badge = badges[state]
        ? `<rect x="49" y="3" width="20" height="20" rx="2" fill="${state === "fault" ? edge : background}"/><g fill="${state === "fault" ? "#FFFFFF" : edge}" transform="translate(51 5) scale(.666667)">${badges[state]}</g>`
        : "";
      const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="72" height="72" viewBox="0 0 72 72"><rect x="2" y="2" width="68" height="68" rx="5" fill="none" stroke="${edge}" stroke-width="${state === "active" || state === "fault" ? 3 : 1}" ${state === "stale" ? 'stroke-dasharray="3 3"' : ""}/><g fill="${fill}" transform="translate(20 ${id === "level" ? 2 : 6}) scale(1.333333)">${path}</g>${badge}</svg>`;
      const png = await sharp(Buffer.from(svg)).png().toBuffer();
      artwork[id][theme][state] = png.toString("base64");
      pngs.push({ id, theme, state, png });
    }
  }
}
const source = `// Generated by scripts/build-artwork.mjs. Do not edit by hand.\n// PrimeIcons 7.0.0: assets/primeicons/LICENSE. Branding: assets/README.md.\nexport const artwork = ${JSON.stringify(artwork, null, 2)} as const;\nexport type ArtworkId = keyof typeof artwork;\n`;
const target = new URL("src/companion/artwork.generated.ts", root);
const fontfile = process.env.ADVATEK_FONT_REGULAR;
if (!fontfile)
  throw new Error(
    "Set ADVATEK_FONT_REGULAR to the licensed FormaDJRDisplay-Regular.otf file. Font files must stay outside the repository.",
  );
const fontSha256 = createHash("sha256")
  .update(await readFile(fontfile))
  .digest("hex");
if (
  fontSha256 !==
  "43fac2b4b7c872070e64ada3ba4ca33d0478aa055c8c3e6779b00ae066f98ac5"
)
  throw new Error(
    "The font does not match the Brand Hub Forma DJR Display Regular source recorded for this review.",
  );
const labels = JSON.parse(
  await readFile(new URL("assets/preset-labels.json", root)),
);
const labelledArtwork = {};
for (const [
  id,
  { icon, label, swatch, level, compactSwatch },
] of Object.entries(labels)) {
  labelledArtwork[id] = {};
  for (const theme of ["dark", "light"]) {
    labelledArtwork[id][theme] = {};
    for (const state of ["idle", "active", "stale", "fault"]) {
      const colour =
        state === "stale"
          ? theme === "dark"
            ? "#B8B7B9"
            : "#78787A"
          : theme === "dark"
            ? "#FFFFFF"
            : "#353436";
      const { data, info } = await sharp({
        text: {
          text: `<span foreground="${colour}">${label}</span>`,
          font: "Forma DJR Display 13",
          fontfile,
          rgba: true,
          align: "center",
          dpi: 72,
        },
      })
        .png()
        .toBuffer({ resolveWithObject: true });
      if (info.width > 66 || info.height > 29)
        throw new Error(
          `Label does not fit: ${id} (${info.width} x ${info.height})`,
        );
      const overlays = [];
      if (swatch) {
        overlays.push({
          input: Buffer.from(
            // Keep the configured swatch colour; borders and badges indicate availability.
            compactSwatch
              ? `<svg xmlns="http://www.w3.org/2000/svg" width="72" height="72"><rect x="20" y="5" width="32" height="16" rx="3" fill="${swatch}" stroke="${theme === "dark" ? "#FFFFFF" : "#353436"}" stroke-width="1.5"/></svg>`
              : `<svg xmlns="http://www.w3.org/2000/svg" width="72" height="72"><rect x="19" y="5" width="34" height="34" rx="17" fill="${theme === "dark" ? "#353436" : "#FFFFFF"}"/><circle cx="36" cy="22" r="13" fill="${swatch}" stroke="${theme === "dark" ? "#FFFFFF" : "#353436"}" stroke-width="1.5"/></svg>`,
          ),
          left: 0,
          top: 0,
        });
      }
      if (level !== undefined) {
        overlays.push({
          input: Buffer.from(
            `<svg xmlns="http://www.w3.org/2000/svg" width="72" height="72"><rect x="18" y="35" width="36" height="2" fill="none" stroke="${colour}"/>${level ? `<rect x="18" y="35" width="${(36 * level) / 100}" height="2" fill="${colour}"/>` : ""}</svg>`,
          ),
          left: 0,
          top: 0,
        });
      }
      // Draw badges last so swatches cannot obscure their warnings.
      if (badges[state]) {
        const background = theme === "dark" ? "#353436" : "#FFFFFF";
        const edge = state === "fault" ? "#B42318" : colour;
        overlays.push({
          input: Buffer.from(
            `<svg xmlns="http://www.w3.org/2000/svg" width="72" height="72"><rect x="49" y="3" width="20" height="20" rx="2" fill="${state === "fault" ? edge : background}"/><g fill="${state === "fault" ? "#FFFFFF" : edge}" transform="translate(51 5) scale(.666667)">${badges[state]}</g></svg>`,
          ),
          left: 0,
          top: 0,
        });
      }
      const png = await sharp(
        Buffer.from(artwork[icon][theme][state], "base64"),
      )
        .composite([
          ...overlays,
          {
            input: data,
            left: Math.floor((72 - info.width) / 2),
            top: 67 - info.height,
          },
        ])
        .png()
        .toBuffer();
      labelledArtwork[id][theme][state] = png.toString("base64");
      pngs.push({ id: `preset-${id}`, theme, state, png });
    }
  }
}
const labelledSource = `// Generated by scripts/build-artwork.mjs. Do not edit by hand.\n// Static label artwork: Forma DJR Display Regular, licensed font source.\n// No font software is embedded. See assets/README.md.\nexport const presetLabels = ${JSON.stringify(labels, null, 2)} as const;\nexport const labelledArtwork: Record<string, {dark: Record<\"idle\" | \"active\" | \"stale\" | \"fault\", string>; light: Record<\"idle\" | \"active\" | \"stale\" | \"fault\", string>}> = ${JSON.stringify(labelledArtwork, null, 2)};\n`;
const labelledTarget = new URL(
  "src/companion/labelled-artwork.generated.ts",
  root,
);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== source)
    throw new Error("Regenerate artwork with yarn artwork:generate");
  if ((await readFile(labelledTarget, "utf8")) !== labelledSource)
    throw new Error("Regenerate the approved-font label artwork.");
} else {
  // Validate the font and all labels before replacing either generated source.
  await writeFile(target, source);
  await writeFile(labelledTarget, labelledSource);
}
// Export files for local review only. The package uses the embedded PNG bytes.
if (process.argv.includes("--export")) {
  const directory = new URL(".local/artwork-review/icons/", root);
  await mkdir(directory, { recursive: true });
  for (const { id, theme, state, png } of pngs)
    await writeFile(new URL(`${id}-${theme}-${state}.png`, directory), png);
}
console.log(
  `Artwork ${process.argv.includes("--check") ? "verified" : "generated"}: ${pngs.length} transparent 72 x 72 PNGs`,
);
