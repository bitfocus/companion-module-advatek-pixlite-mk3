import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const root = new URL("../", import.meta.url);
const bundle = await build({
  configFile: false,
  logLevel: "warn",
  build: {
    target: "es2022",
    write: false,
    minify: true,
    cssCodeSplit: false,
    lib: {
      entry: fileURLToPath(new URL("ui/discovery/main.ts", root)),
      name: "PixLiteDiscovery",
      formats: ["iife"],
    },
  },
});
const output = (Array.isArray(bundle) ? bundle : [bundle]).flatMap(
  (part) => part.output,
);
const script = output.filter((file) => file.type === "chunk");
const styles = output.filter(
  (file) => file.type === "asset" && file.fileName.endsWith(".css"),
);
if (script.length !== 1 || styles.length !== 1 || output.length !== 2)
  throw new Error("Discovery must remain a single self-contained page");
let html = await readFile(new URL("ui/discovery/index.html", root), "utf8");
html = html
  .replace("<!-- STYLE -->", () => `<style>${styles[0].source}</style>`)
  .replace(
    "<!-- SCRIPT -->",
    () =>
      `<script>${script[0].code.replaceAll("</script", "<\\/script")}</script>`,
  );
for (const [name, path] of Object.entries({
  LOGO: "assets/discovery-logo.svg",
  SEARCH: "assets/primeicons/search.svg",
})) {
  const svg = (await readFile(new URL(path, root))).toString().trim();
  html = html.replace(
    `__PIXLITE_${name}__`,
    () => `data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}`,
  );
}
html = html.replace(/>\s+</g, "><").trim();
await writeFile(
  new URL("src/discovery/page.generated.ts", root),
  `// Generated by scripts/build-discovery-page.mjs. Edit ui/discovery instead.\nexport const discoveryHtml = ${JSON.stringify(html)};\n`,
);
console.log(
  `Discovery page: ${Buffer.byteLength(html)} bytes, served entirely by Companion`,
);
